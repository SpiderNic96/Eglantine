#!/usr/bin/env python3
"""Writes src/yuzu/configuration/pokopia_save_names.h: English names of Pokopia 2.0.1's moves,
reactions, items, residents and areas, for the save editor's tabs.

    python save_names.py path/to/PokoHex/PokoHex.Core/Resources/text/en  [out.h]

The lists come from PokoHex (berichan, GPL-3.0), which takes them from the game's own text: one
name per line, the line number being the id the save uses (an empty line is an unused id).
"""
import os
import sys

LISTS = [
    ("skill", "PokopiaSkillNames"),
    ("reaction", "PokopiaReactionNames"),
    ("item", "PokopiaItemNames"),
    ("villager", "PokopiaVillagerNames"),
    ("area", "PokopiaAreaTitles"),
]


def c_string(text):
    out = []
    for ch in text:
        if ch in '\\"':
            out.append("\\" + ch)
        elif ord(ch) < 0x20:
            out.append(" ")
        else:
            out.append(ch)
    return '"' + "".join(out) + '"'


def main():
    if len(sys.argv) < 2:
        sys.exit(__doc__)
    folder = sys.argv[1]
    here = os.path.dirname(os.path.abspath(__file__))
    out_path = sys.argv[2] if len(sys.argv) > 2 else os.path.join(
        here, "..", "..", "src", "yuzu", "configuration", "pokopia_save_names.h")
    lines = [
        "// SPDX-FileCopyrightText: Copyright 2026 Eglantine contributors",
        "// SPDX-License-Identifier: GPL-3.0-or-later",
        "",
        "// Generated by tools/pikantine/save_names.py from PokoHex's English lists (berichan,",
        "// GPL-3.0), which come from the game's text. Index = the id the save uses; \"\" = unused.",
        "",
        "#pragma once",
        "",
        "#include <array>",
        "",
        "namespace Pikantine {",
        "",
    ]
    for name, symbol in LISTS:
        path = os.path.join(folder, f"text_{name}_en.txt")
        with open(path, encoding="utf-8-sig") as f:
            names = f.read().split("\n")
        if names and names[-1] == "":
            names.pop()
        lines.append(f"inline constexpr std::array<const char*, {len(names)}> {symbol}{{")
        for n in names:
            lines.append(f"    {c_string(n.strip())},")
        lines.append("};")
        lines.append("")
    lines.append("} // namespace Pikantine")
    with open(out_path, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    print("wrote", out_path)


if __name__ == "__main__":
    main()
